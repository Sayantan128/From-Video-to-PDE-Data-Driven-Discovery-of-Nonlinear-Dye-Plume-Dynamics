import re
def front_level_to_float(level_key):
    """
    Convert front-level keys like:
        0.05
        "0.05"
        "level_0.050"
    to float.
    """
    if isinstance(level_key, (int, float, np.integer, np.floating)):
        return float(level_key)

    s = str(level_key)

    try:
        return float(s)
    except ValueError:
        pass

    match = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", s)

    if match is None:
        raise ValueError(f"Could not parse numeric level from key: {level_key!r}")

    return float(match.group(0))


def safe_filename(name):
    """
    Convert model/library names into safe filenames.
    """
    return (
        str(name)
        .replace(":", "")
        .replace("|", "")
        .replace("/", "_")
        .replace("\\", "_")
        .replace(" ", "_")
        .replace("+", "plus")
        .replace("^", "pow")
        .replace("·", "dot")
        .replace("(", "")
        .replace(")", "")
        .replace(",", "")
    )


def compute_com_error_over_time(U_true, U_pred, grid):
    """
    Compute center-of-mass distance error at each validation time.
    """
    ny, nx, nt_loc = U_true.shape

    if hasattr(grid, "x"):
        x_local = np.asarray(grid.x)
    else:
        x_local = np.arange(nx) * float(grid.dx)

    if hasattr(grid, "y"):
        y_local = np.asarray(grid.y)
    else:
        y_local = np.arange(ny) * float(grid.dy)

    X, Y = np.meshgrid(x_local, y_local)

    err = []

    for k in range(nt_loc):
        A = np.asarray(U_true[:, :, k])
        B = np.asarray(U_pred[:, :, k])

        mA = np.sum(A) + 1e-12
        mB = np.sum(B) + 1e-12

        cxA = np.sum(A * X) / mA
        cyA = np.sum(A * Y) / mA

        cxB = np.sum(B * X) / mB
        cyB = np.sum(B * Y) / mB

        err.append(np.sqrt((cxB - cxA) ** 2 + (cyB - cyA) ** 2))

    return np.asarray(err, dtype=float)


