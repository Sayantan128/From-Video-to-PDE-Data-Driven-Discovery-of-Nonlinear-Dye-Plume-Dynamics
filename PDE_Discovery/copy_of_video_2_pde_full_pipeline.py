def plot_bootstrap_snapshots(
    U_true,
    U_pred,
    t_val,
    model_name,
    n_show=6,
    cmap="viridis",
    save_path=None,
    show=True,
):
    """
    Plot true and predicted validation snapshots.
    """
    nt_loc = U_true.shape[2]
    ids = np.linspace(0, nt_loc - 1, min(n_show, nt_loc), dtype=int)

    fig, axes = plt.subplots(
        2,
        len(ids),
        figsize=(3.0 * len(ids), 6.0),
        squeeze=False,
    )

    vmin = min(float(np.min(U_true)), float(np.min(U_pred)))
    vmax = max(float(np.max(U_true)), float(np.max(U_pred)))

    for j, k in enumerate(ids):
        ax = axes[0, j]
        ax.imshow(
            U_true[:, :, k],
            cmap=cmap,
            origin="lower",
            vmin=vmin,
            vmax=vmax,
        )
        ax.set_title(f"true\nt={t_val[k]:.2f}")
        ax.axis("off")

        ax = axes[1, j]
        ax.imshow(
            U_pred[:, :, k],
            cmap=cmap,
            origin="lower",
            vmin=vmin,
            vmax=vmax,
        )
        ax.set_title(f"pred\nt={t_val[k]:.2f}")
        ax.axis("off")

    fig.suptitle(f"Snapshots\n{model_name}", fontsize=14)
    plt.tight_layout()

    if save_path is not None:
        fig.savefig(save_path, dpi=300, bbox_inches="tight")

    if show:
        plt.show()
    else:
        plt.close(fig)


def plot_selected_front_comparison(
    t_val,
    fronts_by_model,
    selected_level=0.10,
    save_path=None,
    show=True,
):
    """
    Compare predicted front-radius curves across models
    at a selected threshold level.
    """
    plt.figure(figsize=(9, 5))

    true_plotted = False

    for model_name, front in fronts_by_model.items():
        keys = list(front["per_level"].keys())

        key_float_pairs = [(k, front_level_to_float(k)) for k in keys]

