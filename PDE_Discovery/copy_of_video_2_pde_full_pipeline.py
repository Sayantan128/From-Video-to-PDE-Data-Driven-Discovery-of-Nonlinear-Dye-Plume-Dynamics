def plot_front_radius(t_val, front, model_name, save_path=None, show=True):
    """
    Plot true and predicted equivalent front-radius curves
    for all threshold levels.
    """
    plt.figure(figsize=(8, 4.8))

    for lev, d in front["per_level"].items():
        lev_float = front_level_to_float(lev)

        plt.plot(
            t_val,
            d["r_true"],
            "-",
            label=f"true level {lev_float:.3f}",
        )

        plt.plot(
            t_val,
            d["r_pred"],
            "--",
            label=f"pred level {lev_float:.3f}",
        )

    plt.xlabel("t")
    plt.ylabel("equivalent front radius")
    plt.title(f"Post-bootstrap front radius\n{model_name}")
    plt.grid(True, alpha=0.3)
    plt.legend(fontsize=7, ncol=2)
    plt.tight_layout()

    if save_path is not None:
        plt.savefig(save_path, dpi=300, bbox_inches="tight")

    if show:
        plt.show()
    else:
        plt.close()


