def compute_com_metrics_local(U_true, U_pred, grid):
    """
    Compute center-of-mass MAE/RMSE and error over time.
    """
    ny, nx, nt_loc = U_true.shape

    if hasattr(grid, "x"):
        x_local = np.asarray(grid.x)
    else:
        x_local = np.arange(nx) * float(grid.dx)

    if hasattr(grid, "y"):
        y_local = np.asarray(grid.y)
    else:
        y_local = np.arange(ny) * float(grid.dy)

    X, Y = np.meshgrid(x_local, y_local)

    err = []

    for k in range(nt_loc):
        A = np.asarray(U_true[:, :, k])
        B = np.asarray(U_pred[:, :, k])

        mA = np.sum(A) + 1e-12
        mB = np.sum(B) + 1e-12

        cxA = np.sum(A * X) / mA
        cyA = np.sum(A * Y) / mA

        cxB = np.sum(B * X) / mB
        cyB = np.sum(B * Y) / mB

        err.append(np.sqrt((cxB - cxA) ** 2 + (cyB - cyA) ** 2))

    err = np.asarray(err, dtype=float)

    return {
        "mae": float(np.mean(np.abs(err))),
        "rmse": float(np.sqrt(np.mean(err ** 2))),
        "error_over_time": err,
    }


def compute_front_metrics_local(front):
    """
    Compute front-radius MAE/RMSE from front['per_level'].
    This is robust even if individual levels do not store mae/rmse.
    """
    maes = []
    rmses = []

    for lev, d in front["per_level"].items():
        r_true = np.asarray(d["r_true"], dtype=float)
        r_pred = np.asarray(d["r_pred"], dtype=float)

        diff = r_pred - r_true

        maes.append(float(np.mean(np.abs(diff))))
        rmses.append(float(np.sqrt(np.mean(diff ** 2))))

    return {
        "mae_mean": float(np.mean(maes)),
        "rmse_mean": float(np.mean(rmses)),
    }


