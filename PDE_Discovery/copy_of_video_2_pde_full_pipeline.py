"""# **Chapter 9: Front-radius-aware calibration with positive Laplacian constraint**

## Positive-lap front-aware calibration

The previous bootstrap calibration selected median coefficients by optimizing rollout agreement.  
Here, we perform an additional **front-radius-aware calibration**.

The goal is to improve the geometric/front propagation behavior of the plume.

For the C-family model,

$$
u_t + v(t)\cdot\nabla u
=
a|\nabla u|^2 + \beta \Delta u,
$$

we minimize a combined objective:

$$
J
=
J_{\mathrm{data}}
+
w_f J_{\mathrm{front}}
+
w_g J_{\mathrm{growth}}.
$$
Here:

- $J_{\mathrm{data}}$ is the pixel-wise rollout mismatch;
- $J_{\mathrm{front}}$ measures mismatch in equivalent plume-front radius;
- $J_{\mathrm{growth}}$ measures mismatch in front growth over time.

In this block, we impose the physical constraint

$\beta > 0,$

so that the Laplacian term remains genuinely diffusive.
"""

