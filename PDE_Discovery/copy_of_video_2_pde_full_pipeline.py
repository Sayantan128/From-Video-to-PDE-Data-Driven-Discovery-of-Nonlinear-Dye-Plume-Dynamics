def relative_rmse_percent(U_true, U_pred, eps=1e-12):
    """
    Relative RMSE in percent:
        100 * ||U_pred - U_true||_2 / ||U_true||_2
    """
    num = np.sqrt(np.sum((U_pred - U_true) ** 2))
    den = np.sqrt(np.sum(U_true ** 2)) + eps
    return 100.0 * num / den


def mse_over_time_local(U_true, U_pred):
    """
    Pixel-wise MSE for each time frame.
    """
    return np.mean((U_pred - U_true) ** 2, axis=(0, 1))


def compute_com_error_over_time(U_true, U_pred, grid):
    """
    Center-of-mass distance error for each time frame.
    """
    ny, nx, nt_local = U_true.shape

    if hasattr(grid, "x"):
        x_local = np.asarray(grid.x)
    else:
        x_local = np.arange(nx) * float(grid.dx)

    if hasattr(grid, "y"):
        y_local = np.asarray(grid.y)
    else:
        y_local = np.arange(ny) * float(grid.dy)

    X, Y = np.meshgrid(x_local, y_local)

    err = []

    for k in range(nt_local):
        A = np.asarray(U_true[:, :, k])
        B = np.asarray(U_pred[:, :, k])

        mA = np.sum(A) + 1e-12
        mB = np.sum(B) + 1e-12

        cxA = np.sum(A * X) / mA
        cyA = np.sum(A * Y) / mA

        cxB = np.sum(B * X) / mB
        cyB = np.sum(B * Y) / mB

        err.append(np.sqrt((cxB - cxA) ** 2 + (cyB - cyA) ** 2))

    return np.asarray(err, dtype=float)


def front_radius_curves(U_field, levels, grid):
    """
    Equivalent front radius for superlevel sets {u >= level}.
    """
    dx = float(grid.dx)
    dy = float(grid.dy)
    cell_area = dx * dy

    curves = {}

    for lev in levels:
        lev = float(lev)
        mask = U_field >= lev
        area_t = np.sum(mask, axis=(0, 1)) * cell_area
        r_t = np.sqrt(np.maximum(area_t, 0.0) / np.pi)
        curves[lev] = r_t

    return curves


def compute_front_metrics(U_true, U_pred, levels, grid):
    """
    Compute front-radius MAE/RMSE averaged over levels,
    plus per-level front-growth diagnostics.
    """
    true_curves = front_radius_curves(U_true, levels, grid)
    pred_curves = front_radius_curves(U_pred, levels, grid)

    maes = []
    rmses = []
    rows = []

    for lev in levels:
        lev = float(lev)

        r_true = true_curves[lev]
        r_pred = pred_curves[lev]

        diff = r_pred - r_true

        mae = float(np.mean(np.abs(diff)))
        rmse = float(np.sqrt(np.mean(diff ** 2)))

        true_growth = float(r_true[-1] - r_true[0])
        pred_growth = float(r_pred[-1] - r_pred[0])

        maes.append(mae)
        rmses.append(rmse)

        rows.append({
            "level": lev,
            "front_mae_level": mae,
            "front_rmse_level": rmse,
            "r_true_start": float(r_true[0]),
            "r_true_end": float(r_true[-1]),
            "r_pred_start": float(r_pred[0]),
            "r_pred_end": float(r_pred[-1]),
            "true_growth": true_growth,
            "pred_growth": pred_growth,
            "growth_error": pred_growth - true_growth,
        })

    return {
        "mae_mean": float(np.mean(maes)),
        "rmse_mean": float(np.mean(rmses)),
        "level_rows": rows,
        "true_curves": true_curves,
        "pred_curves": pred_curves,
    }


