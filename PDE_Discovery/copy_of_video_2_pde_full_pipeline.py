import re

def front_level_to_float_final(level_key):
    """
    Convert front-level keys like:
        0.05
        "0.05"
        "level_0.050"
    to float.
    """
    if isinstance(level_key, (int, float, np.integer, np.floating)):
        return float(level_key)

    s = str(level_key)

    try:
        return float(s)
    except ValueError:
        pass

    match = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", s)

    if match is None:
        raise ValueError(f"Could not parse numeric level from key: {level_key!r}")

    return float(match.group(0))


def compute_com_metrics_final(U_true, U_pred, grid):
    """
    Compute center-of-mass MAE/RMSE and error over time.
    """
    ny, nx, nt_loc = U_true.shape

    if hasattr(grid, "x"):
        x_local = np.asarray(grid.x)
    else:
        x_local = np.arange(nx) * float(grid.dx)

    if hasattr(grid, "y"):
        y_local = np.asarray(grid.y)
    else:
        y_local = np.arange(ny) * float(grid.dy)

    X, Y = np.meshgrid(x_local, y_local)

    err = []

    for k in range(nt_loc):
        A = np.asarray(U_true[:, :, k])
        B = np.asarray(U_pred[:, :, k])

        mA = np.sum(A) + 1e-12
        mB = np.sum(B) + 1e-12

        cxA = np.sum(A * X) / mA
        cyA = np.sum(A * Y) / mA

        cxB = np.sum(B * X) / mB
        cyB = np.sum(B * Y) / mB

        err.append(np.sqrt((cxB - cxA) ** 2 + (cyB - cyA) ** 2))

    err = np.asarray(err, dtype=float)

    return {
        "mae": float(np.mean(np.abs(err))),
        "rmse": float(np.sqrt(np.mean(err ** 2))),
        "error_over_time": err,
    }


def compute_front_metrics_final(front):
    """
    Compute front-radius MAE/RMSE from front['per_level'].
    """
    maes = []
    rmses = []
    rows = []

    for lev, d in front["per_level"].items():
        lev_float = front_level_to_float_final(lev)

        r_true = np.asarray(d["r_true"], dtype=float)
        r_pred = np.asarray(d["r_pred"], dtype=float)

        diff = r_pred - r_true

        mae = float(np.mean(np.abs(diff)))
        rmse = float(np.sqrt(np.mean(diff ** 2)))

        true_growth = float(r_true[-1] - r_true[0])
        pred_growth = float(r_pred[-1] - r_pred[0])

        maes.append(mae)
        rmses.append(rmse)

        rows.append({
            "level": lev_float,
            "front_mae_level": mae,
            "front_rmse_level": rmse,
            "r_true_start": float(r_true[0]),
            "r_true_end": float(r_true[-1]),
            "r_pred_start": float(r_pred[0]),
            "r_pred_end": float(r_pred[-1]),
            "true_growth": true_growth,
            "pred_growth": pred_growth,
            "growth_error": pred_growth - true_growth,
        })

    return {
        "mae_mean": float(np.mean(maes)),
        "rmse_mean": float(np.mean(rmses)),
        "level_rows": rows,
    }


